#!/usr/bin/env node
// Source declarations establish coverage, never behavioral or visual verification.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve, relative, join } from 'node:path';
import { createRequire } from 'node:module';
const root = resolve(import.meta.dirname, '../..');
const require = createRequire(join(root, 'apps/web/package.json'));
const ts = require('typescript');
const read = (p) => readFileSync(join(root, p), 'utf8');
function files(dir) {
  return readdirSync(join(root, dir), { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? files(`${dir}/${e.name}`) : [`${dir}/${e.name}`]);
}
const path = (...parts) => ('/' + parts.join('/')).replace(/\/+/g, '/').replace(/\/$/, '') || '/';
const normalize = (p) => p.replace(/:([\w]+)/g, '{$1}').replace(/\[([\w]+)\]/g, '{$1}');
// NestJS controllers were removed from the active tree at Gate M. Endpoint coverage is in
// docs/migration/API_PARITY_MATRIX.md (94/94). This script inventories Spring + Angular only.
const legacy = [];
const spring = [];
for (const file of files('apps/api/src/main/java').filter((f) => f.endsWith('Controller.java'))) {
  const source = read(file);
  const base = source.match(/@RequestMapping\("([^"]*)"\)/)?.[1] ?? '';
  for (const match of source.matchAll(/@(Get|Post|Patch|Put|Delete|Options|Head)Mapping(?:\(\s*"([^"]*)"\s*\))?/g)) {
    spring.push({ key: `${match[1].toUpperCase()} ${path('api', base, match[2] ?? '')}`, file });
  }
}
const angular = new Set();
const sf = ts.createSourceFile('app.routes.ts', read('apps/web/src/app/app.routes.ts'), ts.ScriptTarget.Latest, true);
function visit(node, prefix = '') {
  if (ts.isObjectLiteralExpression(node)) {
    const props = new Map(node.properties.filter(ts.isPropertyAssignment).map((p) => [p.name.getText(sf), p.initializer]));
    const segment = props.get('path');
    if (segment && ts.isStringLiteral(segment)) {
      const full = path(prefix, segment.text);
      if (props.has('component') || props.has('loadComponent')) angular.add(normalize(full));
      const children = props.get('children');
      if (children) visit(children, full);
      return;
    }
  }
  ts.forEachChild(node, (child) => visit(child, prefix));
}
visit(sf);
const preview = read('apps/web/src/app/modules/module-catalog.ts').match(/PREVIEW_MODULE_ROUTES\s*=\s*\[([^\]]+)\]/)?.[1] ?? '';
for (const m of preview.matchAll(/'([^']+)'/g)) angular.add('/' + m[1]);
const pages = files('apps/web/src/app').filter((f) => f.endsWith('/page.tsx')).map((file) => ({
  file, route: normalize(path(relative('apps/web/src/app', file).replaceAll('\\', '/').replace(/\/?page\.tsx$/, ''))),
}));
const springByKey = new Map(spring.map((e) => [e.key, e.file]));
const missingEndpoints = legacy.filter((e) => !springByKey.has(e.key));
const missingPages = pages.filter((e) => !angular.has(e.route));
const lines = [
  '# Source coverage inventory', '',
  'Generated by `node scripts/migration/source-inventory.mjs`. Declarations only: a matching route does not prove functionality, persistence, security, or visual parity.', '',
  `Endpoints: ${legacy.length} legacy, ${spring.length} Spring declarations; ${missingEndpoints.length} missing.`,
  `Pages: ${pages.length} legacy; ${pages.length - missingPages.length} matched Angular routes; ${missingPages.length} missing.`, '',
  '| Endpoint | Legacy controller | Spring controller |', '| --- | --- | --- |',
  ...legacy.sort((a,b) => a.key.localeCompare(b.key)).map((e) => `| \`${e.key}\` | ${e.file} | ${springByKey.get(e.key) ?? '**MISSING**'} |`), '',
  '| Page | Legacy source | Angular declaration |', '| --- | --- | --- |',
  ...pages.sort((a,b) => a.route.localeCompare(b.route)).map((e) => `| \`${e.route}\` | ${e.file} | ${angular.has(e.route) ? 'Present; verification required' : '**MISSING**'} |`), '',
];
writeFileSync(join(root, 'docs/migration/SOURCE_COVERAGE.md'), lines.join('\n'));
console.log(lines.slice(4, 6).join('\n'));
if (process.argv.includes('--require-complete') && (missingEndpoints.length || missingPages.length)) process.exitCode = 1;
