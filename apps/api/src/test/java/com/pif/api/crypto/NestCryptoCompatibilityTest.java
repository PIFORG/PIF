package com.pif.api.crypto;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import com.pif.api.config.PifProperties;
import com.pif.api.security.JwtService;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.LinkedHashMap;
import java.util.Map;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.springframework.mock.env.MockEnvironment;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * Verifies that the Spring implementation reads and produces exactly what the NestJS API does,
 * using fixtures generated by contract/generate-crypto-fixtures.mjs with the NestJS code itself.
 * Artifacts produced here are verified by NestJS in contract/verify-java-artifacts.mjs.
 */
class NestCryptoCompatibilityTest {

  private static final JsonMapper JSON = JsonMapper.builder().build();
  private static JsonNode fixtures;
  private static final Map<String, Object> artifacts = new LinkedHashMap<>();

  @BeforeAll
  static void load() throws Exception {
    try (InputStream in = NestCryptoCompatibilityTest.class.getResourceAsStream("/fixtures/nest-crypto-fixtures.json")) {
      fixtures = JSON.readTree(in);
    }
  }

  @AfterAll
  static void writeArtifacts() throws Exception {
    Path target = Path.of("target", "java-crypto-artifacts.json");
    Files.createDirectories(target.getParent());
    Files.writeString(target, JSON.writerWithDefaultPrettyPrinter().writeValueAsString(artifacts));
  }

  @Test
  void verifiesArgon2idHashesProducedByNodeArgon2() {
    PasswordHasher hasher = new PasswordHasher();
    for (JsonNode c : fixtures.get("argon2")) {
      String hash = c.get("hash").asString();
      assertThat(hash).startsWith("$argon2id$v=19$m=19456,t=2,p=1$");
      assertThat(hasher.verify(hash, c.get("password").asString())).isTrue();
      assertThat(hasher.verify(hash, c.get("password").asString() + "x")).isFalse();
    }
  }

  @Test
  void producesArgon2idHashesInTheSamePhcFormat() {
    PasswordHasher hasher = new PasswordHasher();
    String password = "Pässwörd-✓-java";
    String hash = hasher.hash(password);
    assertThat(hash).matches("^\\$argon2id\\$v=19\\$m=19456,t=2,p=1\\$[A-Za-z0-9+/]{22}\\$[A-Za-z0-9+/]{43}$");
    assertThat(hasher.verify(hash, password)).isTrue();
    artifacts.put("argon2", Map.of("password", password, "hash", hash));
  }

  @Test
  void dummyHashIsWellFormedAndNeverMatches() {
    PasswordHasher hasher = new PasswordHasher();
    assertThat(hasher.verify(PasswordHasher.DUMMY_HASH, "anything")).isFalse();
    assertThat(hasher.verify("not-a-hash", "anything")).isFalse();
  }

  @Test
  void opaqueTokenHashesIpDigestsAndUserAgentsMatch() {
    JsonNode hmac = fixtures.get("hmac");
    String pepper = hmac.get("pepper").asString();
    for (JsonNode t : hmac.get("tokens")) {
      assertThat(TokenCrypto.hashOpaqueToken(t.get("token").asString(), pepper)).isEqualTo(t.get("hash").asString());
    }
    for (JsonNode ip : hmac.get("ips")) {
      assertThat(TokenCrypto.digestIp(ip.get("ip").asString(), pepper)).isEqualTo(ip.get("digest").asString());
    }
    for (JsonNode ua : hmac.get("userAgents")) {
      JsonNode expected = ua.get("sanitized");
      assertThat(TokenCrypto.sanitizeUserAgent(ua.get("ua").asString()))
          .isEqualTo(expected.isNull() ? null : expected.asString());
    }
    assertThat(TokenCrypto.generateOpaqueToken()).matches("^[0-9a-f]{64}$");
  }

  @Test
  void decryptsMfaSecretsEncryptedByNestAndEncryptsInTheSameEnvelope() {
    JsonNode mfa = fixtures.get("mfa");
    String key = mfa.get("key").asString();
    assertThat(MfaCrypto.decrypt(mfa.get("ciphertext").asString(), key)).isEqualTo(mfa.get("plaintext").asString());

    String ciphertext = MfaCrypto.encrypt(mfa.get("plaintext").asString(), key);
    assertThat(ciphertext).startsWith("v1:");
    assertThat(MfaCrypto.decrypt(ciphertext, key)).isEqualTo(mfa.get("plaintext").asString());
    artifacts.put("mfa", Map.of("key", key, "plaintext", mfa.get("plaintext").asString(), "ciphertext", ciphertext));

    String tampered = ciphertext.substring(0, ciphertext.length() - 4) + "AAA=";
    assertThatThrownBy(() -> MfaCrypto.decrypt(tampered, key)).isInstanceOf(IllegalArgumentException.class);
  }

  @Test
  void totpCodesMatchOtplibAuthenticator() {
    JsonNode totp = fixtures.get("totp");
    String secret = totp.get("secret").asString();
    byte[] key = Totp.Base32.decode(secret);
    assertThat(Totp.Base32.encode(key)).isEqualTo(secret.replace("=", ""));
    for (JsonNode v : totp.get("vectors")) {
      long epoch = v.get("epochMs").asLong();
      String code = v.get("code").asString();
      assertThat(Totp.generate(key, Totp.currentStep(epoch))).isEqualTo(code);
      assertThat(Totp.checkDelta(code, secret, epoch)).isEqualTo(0);
      assertThat(Totp.checkDelta(code, secret, epoch + 30_000)).isEqualTo(-1);
      assertThat(Totp.checkDelta(code, secret, epoch + 90_000)).isNull();
    }
    assertThat(Totp.checkDelta("12345", secret, 0)).isNull();
  }

  @Test
  void rfc6238ReferenceVector() {
    byte[] key = "12345678901234567890".getBytes(java.nio.charset.StandardCharsets.US_ASCII);
    // RFC 6238 Appendix B, SHA1, T = 59 s → 94287082 (8 digits); 6-digit truncation → 287082.
    assertThat(Totp.generate(key, 1)).isEqualTo("287082");
  }

  @Test
  void jwtCompatibility() throws Exception {
    JsonNode j = fixtures.get("jwt");
    JwtService service = new JwtService(props(j.get("secret").asString()));
    Instant now = Instant.now();

    JwtService.AccessClaims claims = service.verify(j.get("valid").asString(), now);
    assertThat(claims).isNotNull();
    assertThat(claims.sub()).isEqualTo(j.get("claims").get("sub").asString());
    assertThat(claims.sid()).isEqualTo(j.get("claims").get("sid").asString());
    assertThat(claims.sv()).isEqualTo(j.get("claims").get("sv").asInt());

    assertThat(service.verify(j.get("expired").asString(), now)).isNull();
    assertThat(service.verify(j.get("wrongAudience").asString(), now)).isNull();
    assertThat(service.verify(j.get("wrongIssuer").asString(), now)).isNull();
    assertThat(service.verify(j.get("wrongSecret").asString(), now)).isNull();
    assertThat(service.verify("not.a.jwt", now)).isNull();

    String token = service.sign("11111111-2222-4333-8444-555555555555", "66666666-7777-4888-9999-000000000000", 7, now);
    JwtService.AccessClaims own = service.verify(token, now);
    assertThat(own).isEqualTo(new JwtService.AccessClaims(
        "11111111-2222-4333-8444-555555555555", "66666666-7777-4888-9999-000000000000", 7));
    assertThat(service.verify(token, now.plusSeconds(15 * 60))).as("expired after JWT_ACCESS_EXPIRES_IN").isNull();
    artifacts.put("jwt", Map.of("secret", j.get("secret").asString(), "token", token));
  }

  @Test
  void nodeStyleAddresses() {
    assertThat(TokenCrypto.nodeStyleAddress("127.0.0.1")).isEqualTo("::ffff:127.0.0.1");
    assertThat(TokenCrypto.nodeStyleAddress("0:0:0:0:0:0:0:1")).isEqualTo("::1");
    assertThat(TokenCrypto.nodeStyleAddress("2001:db8:0:0:1:0:0:1")).isEqualTo("2001:db8::1:0:0:1");
    assertThat(TokenCrypto.nodeStyleAddress("fe80:0:0:0:0:0:0:0")).isEqualTo("fe80::");
  }

  static PifProperties props(String jwtSecret) {
    MockEnvironment env = new MockEnvironment()
        .withProperty("JWT_ACCESS_SECRET", jwtSecret)
        .withProperty("AUTH_TOKEN_PEPPER", "test-pepper-not-a-secret")
        .withProperty("AUTH_IP_HASH_PEPPER", "test-ip-pepper-not-a-secret")
        .withProperty("MFA_ENCRYPTION_KEY", "00".repeat(32));
    return new PifProperties(env);
  }
}
