package com.pif.api.finance;

import static com.pif.api.finance.FinanceGoldenCases.list;
import static com.pif.api.finance.FinanceGoldenCases.map;
import static com.pif.api.finance.FinanceGoldenCases.num;
import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.junit.jupiter.api.DynamicContainer.dynamicContainer;
import static org.junit.jupiter.api.DynamicTest.dynamicTest;

import java.io.InputStream;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Predicate;
import java.util.stream.IntStream;
import java.util.stream.Stream;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.DynamicContainer;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.TestFactory;
import tools.jackson.databind.json.JsonMapper;

/**
 * Verifies that com.pif.api.finance computes exactly what the TypeScript financial core
 * (apps/api/src/finance) does, using fixtures generated by contract/generate-finance-fixtures.mjs
 * with the TypeScript code itself. Doubles are compared bit for bit (sign of zero included); no
 * tolerance is needed because both sides perform the same IEEE-754 operations in the same order.
 */
class FinanceGoldenMasterTest {

  private static final JsonMapper JSON = JsonMapper.builder().build();
  private static Map<String, Object> fixture;

  @BeforeAll
  static void load() throws Exception {
    try (InputStream in = FinanceGoldenMasterTest.class.getResourceAsStream("/fixtures/finance-golden.json")) {
      fixture = map(JSON.readValue(in, Map.class));
    }
  }

  @TestFactory
  Stream<DynamicContainer> everyGoldenCaseMatchesTypeScript() {
    return map(fixture.get("golden")).entrySet().stream().map(fn -> {
      List<Object> cases = list(fn.getValue());
      return dynamicContainer(fn.getKey(), IntStream.range(0, cases.size()).mapToObj(i -> {
        Map<String, Object> c = map(cases.get(i));
        String name = "#" + i + (c.get("note") == null ? "" : " " + c.get("note"));
        return dynamicTest(name, () -> FinanceGoldenCases.check(fn.getKey(), c));
      }));
    });
  }

  @Test
  void fixtureCoversEveryExportedFunction() {
    Map<String, Object> golden = map(fixture.get("golden"));
    assertThat(golden.keySet()).containsExactlyInAnyOrderElementsOf(FinanceGoldenCases.FUNCTIONS);
    golden.forEach((fn, cases) -> assertThat(list(cases)).as(fn).hasSizeGreaterThanOrEqualTo(5));
  }

  @Test
  void constantsMatch() {
    Map<String, Object> constants = map(fixture.get("constants"));
    assertThat(num(constants.get("AMOUNT_SCALE"))).isEqualTo(Money.AMOUNT_SCALE);
    assertThat(num(constants.get("MIN_VOLATILITY_RETURNS"))).isEqualTo(Risk.MIN_VOLATILITY_RETURNS);
    assertThat(num(constants.get("MIN_VAR_OBSERVATIONS"))).isEqualTo(Risk.MIN_VAR_OBSERVATIONS);
  }

  /**
   * TypeScript keeps positions in a plain object, so a symbol named like an Object.prototype member
   * resolves to the prototype: the buy is charged but the holding is lost ("__proto__" even
   * pollutes every object). Java books such symbols like any other.
   */
  @Test
  void prototypeMemberNamesAreOrdinarySymbolsInJava() {
    for (Object o : list(divergences().get("prototypeSymbols"))) {
      Map<String, Object> p = map(o);
      String symbol = (String) p.get("symbol");
      assertThat(p.get("ownPositionKeys")).as("TypeScript drops the %s holding", symbol).isEqualTo(List.of());

      Ledger ledger = Ledger.empty(1_000_000);
      Booking booking = Ledger.bookExecution(ledger, new Execution(symbol, OrderSide.BUY, 10_000, 10, 500, 9_990));
      FinanceGoldenCases.compare(symbol + " booking", p.get("booking"), Map.of(
          "notional", booking.notional(), "fee", booking.fee(), "spreadCost", booking.spreadCost(),
          "costRemoved", booking.costRemoved(), "realizedPnl", booking.realizedPnl()));
      assertThat(ledger.cash()).isEqualTo(num(p.get("cashAfter")));
      assertThat(ledger.positions()).containsExactly(Map.entry(symbol, new Holding(symbol, 10, 100_500)));
      assertThat(Ledger.heldQuantity(ledger, symbol)).isEqualTo(10);
      assertThat(Valuation.marketValues(Map.of("K", new Holding(symbol, 2, 0)), s -> 100)).containsExactly(Map.entry(symbol, 200.0));
    }
  }

  /**
   * TypeScript sorts stress lines with localeCompare (ICU, server locale); Java uses the JDK
   * root-locale collator. Both agree on letters, digits, case and accents (golden cases); they
   * differ only on where spaces and punctuation sort. Lines and total are identical.
   */
  @Test
  void stressLinesMatchAndOnlySymbolsWithSpacesOrPunctuationSortDifferently() {
    Map<String, Object> collation = map(divergences().get("collation"));
    Map<String, Object> ts = map(collation.get("output"));
    Map<String, Object> java = FinanceGoldenCases.stress(Risk.stressImpact(FinanceGoldenCases.amounts(collation.get("values")), s -> -0.1));

    FinanceGoldenCases.compare("impact", ts.get("impact"), java.get("impact"));
    FinanceGoldenCases.compare("lines by symbol", bySymbol(ts), bySymbol(java));
    Predicate<String> lettersAndDigits = s -> s.chars().allMatch(Character::isLetterOrDigit);
    assertThat(symbols(java).stream().filter(lettersAndDigits).toList()).isEqualTo(symbols(ts).stream().filter(lettersAndDigits).toList());
    assertThat(symbols(java)).isNotEqualTo(symbols(ts));
  }

  /** Golden cases whose TypeScript VaR came from ±Infinity in the sample; they now verify the refusal instead. */
  @Test
  void exactlyTwoGoldenValueAtRiskCasesAreReclassifiedAsInvalidData() {
    List<Object> cases = list(map(fixture.get("golden")).get("historicalVaR"));
    long refused = cases.stream().map(FinanceGoldenCases::map)
        .filter(c -> FinanceGoldenCases.isRefusedVarSample("historicalVaR", map(c.get("input")))).count();
    assertThat(refused).isEqualTo(2);
    assertThat(cases.size() - refused).as("historicalVaR cases still compared bit for bit").isGreaterThanOrEqualTo(5);
  }

  /** With NaN in the sample, the TypeScript result depends on V8's sort internals; Java refuses the sample. */
  @Test
  void valueAtRiskOfSamplesWithNaNIsRefused() {
    for (Object o : list(divergences().get("historicalVaRWithNaN"))) {
      double[] pnl = FinanceGoldenCases.numbers(map(map(o).get("input")).get("pnl"));
      assertThatThrownBy(() -> Risk.historicalVaR(pnl)).isInstanceOf(InvalidSampleException.class);
    }
  }

  /** TypeScript spreads every weight into Math.max, which overflows the call stack for very large portfolios. */
  @Test
  void maxWeightHasNoHoldingCountLimit() {
    Map<String, Object> limit = map(divergences().get("maxWeightStackLimit"));
    assertThat(map(limit.get("error")).get("message")).isEqualTo("Maximum call stack size exceeded");
    Map<String, Double> values = new LinkedHashMap<>();
    for (int i = 0; i < (int) num(limit.get("holdings")); i++) values.put("S" + i, num(limit.get("valueEach")));
    assertThat(Valuation.maxWeight(values, num(limit.get("base")))).isEqualTo(0.1);
  }

  private static Map<String, Object> divergences() {
    return map(fixture.get("divergences"));
  }

  private static List<String> symbols(Map<String, Object> stress) {
    List<String> out = new ArrayList<>();
    for (Object line : list(stress.get("breakdown"))) out.add((String) map(line).get("symbol"));
    return out;
  }

  private static Map<String, Object> bySymbol(Map<String, Object> stress) {
    Map<String, Object> out = new LinkedHashMap<>();
    for (Object line : list(stress.get("breakdown"))) out.put((String) map(line).get("symbol"), line);
    return out;
  }
}
